-- Services Users book in a salon's slots (/api/booking/*). Same columns as wl_orders, plus the booking fields.
-- InnoDB (not MyISAM like wl_orders) so a booking and the slot's booked count are saved together.
-- Run once on the beaunic database before using the booking APIs (needs wl_booking_slots from 0006).
CREATE TABLE `wl_bookings` (
  `booking_id` int NOT NULL AUTO_INCREMENT COMMENT 'Unique booking ID',
  `customer_id` int NOT NULL DEFAULT '0' COMMENT 'Customer ID - References wl_customers (User, customer_type 2, who booked)',
  `customer_type` varchar(100) COLLATE utf8mb4_unicode_ci DEFAULT 'Member',
  `invoice_number` varchar(30) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Invoice number (the booking ID, as in wl_orders)',
  `first_name` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `last_name` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `mobile_number` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `phone` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `email` varchar(50) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `discount_coupon_id` int NOT NULL DEFAULT '0',
  `discount_coupon_code` varchar(40) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `coupon_discount_amount` float(10,2) DEFAULT NULL,
  `total_amount` decimal(10,2) NOT NULL DEFAULT '0.00',
  `vat_amount` decimal(10,2) DEFAULT '0.00',
  `vat_applied_cent` float(10,2) NOT NULL DEFAULT '0.00',
  `currency_code` char(3) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `currency_symbol` char(10) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `currency_value` decimal(14,6) NOT NULL DEFAULT '0.000000',
  `order_status` varchar(10) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'Placed' COMMENT 'Booked, Completed, Cancelled, No Show',
  `order_received_date` datetime DEFAULT NULL COMMENT 'Date and time when the booking was made',
  `payment_method` varchar(200) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `payment_status` enum('Paid','Unpaid') COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'Unpaid',
  `salon_id` int NOT NULL COMMENT 'Salon ID - References wl_customers (Salon Partner, customer_type 1, providing the service)',
  `service_id` int NOT NULL COMMENT 'Service ID - References wl_services (booked service)',
  `slot_id` int NOT NULL COMMENT 'Slot ID - References wl_booking_slots (booked slot)',
  `service_name` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Service name when booked',
  `service_price` decimal(10,2) NOT NULL DEFAULT '0.00' COMMENT 'Service price when booked',
  `slot_date` date NOT NULL COMMENT 'Slot date when booked',
  `start_time` time NOT NULL COMMENT 'Slot start time when booked',
  `end_time` time NOT NULL COMMENT 'Slot end time when booked',
  `booking_notes` text COLLATE utf8mb4_unicode_ci COMMENT 'Optional note from the customer',
  `booking_cancelled_date` datetime DEFAULT NULL COMMENT 'Date and time when the booking was cancelled',
  `booking_updated_date` datetime DEFAULT NULL COMMENT 'Date and time when the booking was last updated',
  PRIMARY KEY (`booking_id`),
  KEY `idx_bookings_customer_id` (`customer_id`),
  KEY `idx_bookings_salon_id` (`salon_id`),
  KEY `idx_bookings_slot_customer` (`slot_id`, `customer_id`),
  CONSTRAINT `wl_bookings_customer_id_fk` FOREIGN KEY (`customer_id`) REFERENCES `wl_customers` (`customer_id`),
  CONSTRAINT `wl_bookings_salon_id_fk` FOREIGN KEY (`salon_id`) REFERENCES `wl_customers` (`customer_id`),
  CONSTRAINT `wl_bookings_service_id_fk` FOREIGN KEY (`service_id`) REFERENCES `wl_services` (`service_id`),
  CONSTRAINT `wl_bookings_slot_id_fk` FOREIGN KEY (`slot_id`) REFERENCES `wl_booking_slots` (`slot_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Services users book in salon slots';
