-- Times a Salon Partner picks for a slot (/api/slot/times); /api/slot/create and /api/slot/update take their IDs.
-- Run once on the beaunic database BEFORE deploying the code that uses it.
CREATE TABLE `wl_times` (
  `time_id` int NOT NULL AUTO_INCREMENT COMMENT 'Unique time ID',
  `time_value` time NOT NULL COMMENT '24-hour time, e.g. 14:30:00',
  `time_label` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '' COMMENT 'Time as shown, e.g. 02:30 PM',
  `sort_order` int DEFAULT NULL,
  `status` enum('1','0','2') COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT '1' COMMENT 'Status: 1 = Active, 0 = Inactive, 2 = Deleted',
  `time_added_date` datetime DEFAULT NULL,
  `time_updated_date` datetime DEFAULT NULL,
  PRIMARY KEY (`time_id`),
  UNIQUE KEY `uq_times_time_value` (`time_value`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Times offered for booking slots';

