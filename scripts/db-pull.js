/**
 * Introspects the MySQL database and writes Drizzle schema files to src/schema.
 *
 * Step 1 runs `drizzle-kit introspect` with runtime patches for drizzle-kit
 * 0.31.x MySQL codegen bugs (the installed package is not modified; a
 * patched copy is written next to it):
 *   - enum columns with numeric-looking defaults (enum('1','2') DEFAULT '2')
 *     are parsed as JS numbers, crashing codegen with
 *     "TypeError: str.replace is not a function".
 *   - float(p,s) columns with a DB name are emitted without a comma:
 *     float("col"{ precision: 10, scale: 2 }).
 *   - DEFAULT '' is emitted as .default(') (unterminated string).
 *   - numeric DEFAULT 0 / 0.00 is silently dropped (falsy check).
 *
 * Step 2 splits the generated drizzle/schema.ts into one file per table
 * under src/schema as CommonJS .js, plus an index.js barrel. Column types
 * drizzle-kit cannot parse (blob) are mapped to custom types in
 * src/schema/custom-types.js;
 * any other unparsed column aborts the run instead of being dropped.
 *
 * Read-only against the database: introspection only runs SELECTs on
 * information_schema.
 */
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const kitDir = path.join(root, 'node_modules', 'drizzle-kit');
const binPath = path.join(kitDir, 'bin.cjs');
const patchedPath = path.join(kitDir, 'bin.introspect-patched.cjs');

const PATCHES = [
  {
    name: 'enum numeric default',
    buggy: '!["decimal", "char", "varchar"].some((type) => columnType.startsWith(type))',
    fixed: '!["decimal", "char", "varchar", "enum"].some((type) => columnType.startsWith(type))',
  },
  {
    name: 'float missing comma',
    buggy: 'float(${dbColumnName3({ name, casing: rawCasing })}${params ? timeConfig(params) : ""})',
    fixed: 'float(${dbColumnName3({ name, casing: rawCasing, withMode: params !== void 0 })}${params ? timeConfig(params) : ""})',
  },
  {
    // DEFAULT '' is emitted as .default(') because '' collapses to a lone quote
    name: 'empty string default',
    buggy: 'function unescapeSingleQuotes(str, ignoreFirstAndLastChar) {\n',
    fixed: 'function unescapeSingleQuotes(str, ignoreFirstAndLastChar) {\n  if (str === "\'\'") return str;\n',
  },
  {
    // numeric DEFAULT 0 is dropped by `defaultValue ? ... : ""` checks
    name: 'zero default',
    buggy: 'column8 = (type, name, casing2, rawCasing, defaultValue, autoincrement, onUpdate, isExpression) => {\n',
    fixed: 'column8 = (type, name, casing2, rawCasing, defaultValue, autoincrement, onUpdate, isExpression) => {\n      if (typeof defaultValue === "number") defaultValue = String(defaultValue);\n',
  },
];

// Types drizzle-kit can't introspect -> custom type exported from custom-types.js
const CUSTOM_TYPES = ['blob'];

function patchKit() {
  let src = fs.readFileSync(binPath, 'utf8');
  for (const p of PATCHES) {
    if (src.includes(p.buggy)) src = src.split(p.buggy).join(p.fixed);
    else if (!src.includes(p.fixed)) console.warn(`[db-pull] patch "${p.name}" not applicable to this drizzle-kit version`);
  }
  fs.writeFileSync(patchedPath, src);
  return patchedPath;
}

function introspect() {
  const bin = patchKit();
  const res = spawnSync(process.execPath, [bin, 'introspect', '--config', 'drizzle.config.js'], {
    cwd: root,
    stdio: 'inherit',
  });
  if (res.status !== 0) process.exit(res.status ?? 1);
}

const toKebab = (s) => s.replace(/_/g, '-');
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const CUSTOM_TYPES_SOURCE = `// Generated by scripts/db-pull.js. Column types drizzle-orm/mysql-core has no builder for.
const { customType } = require("drizzle-orm/mysql-core");

// Maps MySQL BLOB to a Node.js Buffer
const blob = customType({
	dataType() {
		return "blob";
	},
});

module.exports = { blob };
`;

function splitSchema() {
  const generated = path.join(root, 'drizzle', 'schema.ts');
  const outDir = path.join(root, 'src', 'schema');
  const src = fs.readFileSync(generated, 'utf8');

  // Each table is a top-level `export const x = mysqlTable(...)` block ending at `});`
  const blocks = src.split(/\n(?=export const )/).filter((b) => b.startsWith('export const '));
  if (blocks.length === 0) throw new Error('No tables found in drizzle/schema.ts');

  const coreImports = [
    'mysqlTable', 'mysqlSchema', 'mysqlEnum', 'mysqlView',
    'primaryKey', 'index', 'uniqueIndex', 'unique', 'foreignKey', 'check',
    'int', 'tinyint', 'smallint', 'mediumint', 'bigint', 'serial',
    'decimal', 'double', 'float', 'real', 'boolean',
    'char', 'varchar', 'text', 'tinytext', 'mediumtext', 'longtext',
    'binary', 'varbinary', 'date', 'datetime', 'time', 'timestamp', 'year', 'json',
  ];

  fs.mkdirSync(outDir, { recursive: true });
  for (const f of fs.readdirSync(outDir)) {
    if (/\.(js|ts)$/.test(f) || f === 'tsconfig.json') fs.unlinkSync(path.join(outDir, f));
  }
  fs.writeFileSync(path.join(outDir, 'custom-types.js'), CUSTOM_TYPES_SOURCE);

  const exportsList = [];
  const unparsed = [];
  for (let block of blocks) {
    block = block.trimEnd() + '\n';
    const exportName = block.match(/^export const (\w+)/)[1];
    const tableName = (block.match(/mysqlTable\("([^"]+)"/) || [])[1] || exportName;

    // drizzle-kit comments out columns it can't parse; restore known ones via custom types
    block = block.replace(
      /^(\s*)\/\/ Warning: Can't parse (\w+) from database\r?\n\s*\/\/ \w+: \w+\("([^"]+)"\)(.*)$/gm,
      (match, indent, type, col, rest) => {
        if (!CUSTOM_TYPES.includes(type)) {
          unparsed.push(`${tableName}.${col} (${type})`);
          return match;
        }
        return `${indent}${camel(col)}: ${type}("${col}")${rest}`;
      },
    );
    if (/Can't parse/.test(block) && !unparsed.some((u) => u.startsWith(`${tableName}.`))) {
      unparsed.push(`${tableName} (unrecognised warning)`);
    }

    // TypeScript -> CommonJS: drop type annotations and the ESM export
    block = block
      .replace(/\(\): AnyMySqlColumn =>/g, '() =>')
      .replace(/^export const /, 'const ');
    if (/AnyMySqlColumn|: \w+\s*=>|<[A-Z]\w*>/.test(block)) {
      throw new Error(`[db-pull] Unhandled TypeScript syntax in ${tableName}`);
    }

    const used = coreImports.filter((name) => new RegExp(`(?<![.\\w])${name}\\(`).test(block));
    if (!used.includes('mysqlTable')) used.unshift('mysqlTable');
    const custom = CUSTOM_TYPES.filter((name) => new RegExp(`(?<![.\\w])${name}\\(`).test(block));
    const header = [
      `const { ${used.join(', ')} } = require("drizzle-orm/mysql-core");`,
      /\bsql`/.test(block) ? 'const { sql } = require("drizzle-orm");' : null,
      custom.length ? `const { ${custom.join(', ')} } = require("./custom-types");` : null,
    ].filter(Boolean).join('\n');
    const fileBase = toKebab(tableName);
    fs.writeFileSync(path.join(outDir, `${fileBase}.js`), `${header}\n\n${block}\nmodule.exports = { ${exportName} };\n`);
    exportsList.push({ exportName, fileBase, tableName });
  }

  if (unparsed.length) {
    throw new Error(`[db-pull] Columns drizzle-kit could not parse (add a custom type):\n  ${unparsed.join('\n  ')}`);
  }

  exportsList.sort((a, b) => a.fileBase.localeCompare(b.fileBase));
  const index = 'module.exports = {\n'
    + exportsList.map((e) => `  ...require("./${e.fileBase}"),`).join('\n')
    + '\n};\n';
  fs.writeFileSync(path.join(outDir, 'index.js'), index);

  console.log(`[db-pull] Wrote ${exportsList.length} table files + index.js to src/schema`);
  return exportsList;
}

if (require.main === module) {
  if (!process.argv.includes('--split-only')) introspect();
  splitSchema();
}

module.exports = { splitSchema };
